export type StringKey = keyof typeof S

let lang: 0 | 1 = navigator.language.toLowerCase().startsWith('de') ? 0 : 1

export function setLocale(locale: string): void {
  lang = locale.toLowerCase().startsWith('de') ? 0 : 1
}

export function t(key: StringKey): string {
  return S[key][lang]
}

export function isGerman(): boolean {
  return lang === 0
}

export function localeTag(): string {
  return lang === 0 ? 'de-DE' : 'en-US'
}

export function pick<T>(v: { de: T; en: T }): T {
  return lang === 0 ? v.de : v.en
}

export function fmtTime(sec: number): string {
  const s = Math.max(0, Math.round(sec))
  const m = Math.floor(s / 60)
  return `${m}:${String(s % 60).padStart(2, '0')}`
}

export function fmtSeconds(sec: number): string {
  return `${sec.toLocaleString(localeTag(), { maximumFractionDigits: 1, minimumFractionDigits: 1 })} s`
}
