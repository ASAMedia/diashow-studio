// The app icon: renders build/icon.svg (24 px and up) and build/icon-small.svg (16 and 20 px) with
// sharp and writes
//   build/icon.ico        Windows icon with 16, 20, 24, 32, 48, 64, 128 and 256 px (exe, installer,
//                         uninstaller, window; see electron-builder.yml and src/main/index.ts)
//   build/icon.png        256 px PNG (previews, README)
//   src/main/share/favicon.ts   a 64 px PNG as data URI for the phone pages of "Share over Wi-Fi"
// The results are committed; run `node scripts/make-icon.mjs` again after changing the SVGs.
// Sizes below 256 are stored as 32-bit BMP (what every Windows tool reads), 256 px as PNG.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const build = join(root, 'build')
const large = readFileSync(join(build, 'icon.svg'))
const small = readFileSync(join(build, 'icon-small.svg'))
const SIZES = [16, 20, 24, 32, 48, 64, 128, 256]

/** The icon as RGBA pixels (or PNG) at `size` px, from the SVG drawn for that size. */
function render(size) {
  const svg = size <= 20 ? small : large
  const base = size <= 20 ? 16 : 256
  // render a little larger than needed, then scale down: smoother edges
  return sharp(svg, { density: Math.max(72, (72 * size * 4) / base) }).resize(size, size, { kernel: 'lanczos3' })
}

/** A 32-bit BMP icon image (BITMAPINFOHEADER, bottom-up BGRA, empty AND mask). */
function bmpEntry(rgba, size) {
  const rowMask = Math.ceil(size / 32) * 4
  const header = Buffer.alloc(40)
  header.writeUInt32LE(40, 0)
  header.writeInt32LE(size, 4)
  header.writeInt32LE(size * 2, 8) // colour image + mask
  header.writeUInt16LE(1, 12)
  header.writeUInt16LE(32, 14)
  header.writeUInt32LE(0, 16)
  header.writeUInt32LE(size * size * 4 + rowMask * size, 20)
  const pixels = Buffer.alloc(size * size * 4)
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const src = ((size - 1 - y) * size + x) * 4
      const dst = (y * size + x) * 4
      pixels[dst] = rgba[src + 2]
      pixels[dst + 1] = rgba[src + 1]
      pixels[dst + 2] = rgba[src]
      pixels[dst + 3] = rgba[src + 3]
    }
  }
  return Buffer.concat([header, pixels, Buffer.alloc(rowMask * size)])
}

const images = []
for (const size of SIZES) {
  const png = await render(size).png({ compressionLevel: 9 }).toBuffer()
  if (size >= 256) images.push({ size, data: png })
  else images.push({ size, data: bmpEntry(await render(size).ensureAlpha().raw().toBuffer(), size) })
  if (size === 256) writeFileSync(join(build, 'icon.png'), png)
}

const dir = Buffer.alloc(6 + 16 * images.length)
dir.writeUInt16LE(0, 0)
dir.writeUInt16LE(1, 2)
dir.writeUInt16LE(images.length, 4)
let offset = dir.length
images.forEach(({ size, data }, i) => {
  const at = 6 + 16 * i
  dir.writeUInt8(size >= 256 ? 0 : size, at)
  dir.writeUInt8(size >= 256 ? 0 : size, at + 1)
  dir.writeUInt8(0, at + 2)
  dir.writeUInt8(0, at + 3)
  dir.writeUInt16LE(1, at + 4)
  dir.writeUInt16LE(32, at + 6)
  dir.writeUInt32LE(data.length, at + 8)
  dir.writeUInt32LE(offset, at + 12)
  offset += data.length
})
const ico = Buffer.concat([dir, ...images.map((x) => x.data)])
writeFileSync(join(build, 'icon.ico'), ico)

const favicon = await render(64).png({ compressionLevel: 9, palette: true }).toBuffer()
writeFileSync(
  join(root, 'src', 'main', 'share', 'favicon.ts'),
  `// Generated by scripts/make-icon.mjs from build/icon.svg: the app icon for the phone pages (64 px PNG).\nexport const FAVICON = 'data:image/png;base64,${favicon.toString('base64')}'\n`
)
console.log(`build/icon.ico: ${images.map((x) => x.size).join(', ')} px, ${ico.length} bytes; favicon ${favicon.length} bytes`)
